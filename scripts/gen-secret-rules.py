#!/usr/bin/env python3
# Generates internal/secrets/rules_gen.go from internal/secrets/gitleaks.toml,
# gitleaks' default rule set (MIT, see internal/secrets/LICENSE.gitleaks)
# Output is sorted and has no timestamps
# Rules this scanner can't apply faithfully are left out and
# listed in the output with the reason for each
#
#   curl -sSo internal/secrets/gitleaks.toml \
#     https://raw.githubusercontent.com/gitleaks/gitleaks/vX.Y.Z/config/gitleaks.toml
#   python3 scripts/gen-secret-rules.py && gofmt -w internal/secrets/rules_gen.go

import json, pathlib, sys, tomllib

root = pathlib.Path(__file__).resolve().parent.parent
src = root / "internal/secrets/gitleaks.toml"
out = root / "internal/secrets/rules_gen.go"
cfg = tomllib.loads(src.read_text())

EXCLUDED = {"generic-api-key": "matches any random-looking value assigned to a name like key or token"}

def gostr(s):
    if "`" not in s:
        return "`" + s + "`"
    return json.dumps(s)

def golist(xs):
    return "[]string{" + ", ".join(gostr(x) for x in xs) + "}"

def allow(a, where):
    unknown = set(a) - {"description", "regexes", "regexTarget", "stopwords", "condition", "paths", "commits"}
    if unknown:
        sys.exit(f"{where}: unsupported allowlist keys {sorted(unknown)}")
    target = a.get("regexTarget", "secret")
    if target not in ("secret", "match", "line"):
        sys.exit(f"{where}: regexTarget {target!r}")
    cond = a.get("condition", "OR").upper()
    if cond == "AND" and (a.get("paths") or a.get("commits")):
        return None
    if not a.get("regexes") and not a.get("stopwords"):
        return None
    return (f"{{target: {gostr(target)}, and: {str(cond == 'AND').lower()}, "
            f"regexes: {golist(a.get('regexes', []))}, stopwords: {golist([w.lower() for w in a.get('stopwords', [])])}}}")

rules, skipped = [], []
for r in sorted(cfg["rules"], key=lambda r: r["id"]):
    rid = r["id"]
    if rid in EXCLUDED:
        skipped.append((rid, EXCLUDED[rid])); continue
    if "regex" not in r:
        skipped.append((rid, "matches file paths, not content")); continue
    if "path" in r:
        skipped.append((rid, "applies only to some file paths")); continue
    unknown = set(r) - {"id", "description", "regex", "keywords", "entropy", "secretGroup", "allowlists", "tags"}
    if unknown:
        sys.exit(f"{rid}: unsupported keys {sorted(unknown)}")
    allows = [x for x in (allow(a, rid) for a in r.get("allowlists", [])) if x]
    rules.append(
        f"\t{{\n\t\tid: {gostr(rid)},\n\t\tdescription: {gostr(r['description'])},\n"
        f"\t\tregex: {gostr(r['regex'])},\n\t\tkeywords: {golist([k.lower() for k in r.get('keywords', [])])},\n"
        f"\t\tentropy: {r.get('entropy', 0)},\n\t\tsecretGroup: {r.get('secretGroup', 0)},\n"
        f"\t\tallow: []allowlist{{{', '.join(allows)}}},\n\t}},")

g = cfg.get("allowlist", {})
glob = allow({k: v for k, v in g.items() if k != "paths"}, "global") or "{}"

lines = ["// Code generated by scripts/gen-secret-rules.py from gitleaks.toml; DO NOT EDIT.", "",
         "// The rules are gitleaks' default configuration, Copyright (c) 2019 Zachary Rice,",
         "// MIT License (LICENSE.gitleaks). " + cfg.get("title", ""), "",
         "package secrets", "",
         "// Rules left out:"]
lines += [f"//   - {rid}: {why}" for rid, why in skipped]
lines += ["", "var globalAllow = allowlist" + glob, "", "var ruleSpecs = []ruleSpec{"] + rules + ["}", ""]
out.write_text("\n".join(lines))
print(f"{len(rules)} rules, {len(skipped)} left out", file=sys.stderr)
